def normalize_language(value: str | None) -> str:
    return "en" if str(value or "").lower().startswith("en") else "pt"


def translate(key: str, language: str = "pt", **values) -> str:
    language = normalize_language(language)
    message = MESSAGES[language].get(key, MESSAGES["pt"].get(key, key))
    return message.format(**values) if values else message
